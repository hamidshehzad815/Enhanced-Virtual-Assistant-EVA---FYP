def T(text: str, *entities: str) -> dict[str, Any]:
    """Return a single template dict with text and entity slot list."""
    return {"text": text, "entities": list(entities)}


def G(
    id: str,
    label: str,
    styles: list[str],
    *templates: dict[str, Any],
) -> dict[str, Any]:
    """Return a template group dict."""
    return {
        "id": id,
        "label": label,
        "styles": styles,
        "templates": list(templates),
    }


