def count_templates(intent_dict: dict[str, Any]) -> int:
    return sum(len(group["templates"]) for group in intent_dict["groups"])


def export_json(intent_dict: dict[str, Any], output_dir: Path) -> Path:
    output_path = output_dir / f"{intent_dict['intent']}.json"
    with output_path.open("w", encoding="utf-8") as fh:
        json.dump(intent_dict, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return output_path


